  if (coords[0][0]!==coords[coords.length-1][0] || coords[0][1]!==coords[coords.length-1][1]) {
    coords.push(coords[0]);
  }
  const geojson = {
    type:'Feature',
    properties:{ name:r.name, key:r.key, source:'simplified-approximation', note:'sgis.kostat.go.kr 공식 데이터 교체 권장' },
    geometry:{ type:'Polygon', coordinates:[coords] }
  };
  fs.writeFileSync(base+key+'.geojson', JSON.stringify(geojson, null, 2), 'utf8');
  console.log('✅ '+key+'.geojson ('+coords.length+'개 좌표)');
